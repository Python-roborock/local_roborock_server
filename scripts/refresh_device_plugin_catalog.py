"""Rebuild the built-in device plugin catalog from the Roborock cloud.

Without a cloud snapshot, the server answers /api/v5/product and
/api/v1/appplugin from this catalog. Any Roborock account works, also one
without devices:

    uv run python scripts/refresh_device_plugin_catalog.py --email you@example.com
    uv run python scripts/refresh_device_plugin_catalog.py --source-json login.json

The first form asks Roborock for a login code and reads it from the terminal.
The second form reuses a stored login, in the formats that
import_web_inventory_from_cloud.py --source-json accepts. The script makes two
cloud requests and writes no login data.
"""

from __future__ import annotations

import argparse
import asyncio
import importlib
import json
import sys
from collections.abc import Awaitable, Callable
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import aiohttp
from roborock.data import UserData
from roborock.web_api import RoborockApiClient

# The script edits the catalog in this checkout. It does not import the server,
# because the server needs the catalog to start.
BACKEND_PATH = Path(__file__).resolve().parents[1] / "src" / "roborock_local_server" / "bundled_backend"
if str(BACKEND_PATH) not in sys.path:
    sys.path.insert(0, str(BACKEND_PATH))
# Loaded after the path change above.
importer = importlib.import_module("import_web_inventory_from_cloud")
as_int = importlib.import_module("shared.data_helpers").as_int

# Read by shared/device_plugin_catalog.py.
CATALOG_PATH = BACKEND_PATH / "shared" / "device_plugin_catalog.json"

PRODUCTS_PATH = "/api/v5/product"
APPPLUGIN_PATH = "/api/v1/appplugin"
# The Android app 4.60.06 sends type 2 and apilevel 10046. The cloud answers
# the newest plugin that this app can load.
APP_TYPE_ANDROID = 2
APP_API_LEVEL = 10046

CloudCall = Callable[..., Awaitable[Any]]


def _product_entries(products: Any) -> list[tuple[str, dict[str, Any]]]:
    entries: list[tuple[str, dict[str, Any]]] = []
    category_details = products.get("categoryDetailList") if isinstance(products, dict) else None
    for category_detail in category_details or []:
        category = (category_detail or {}).get("category") or {}
        for product in (category_detail or {}).get("productList") or []:
            model = str(product.get("model") or "").strip().lower()
            product_id = as_int(product.get("id"), 0)
            if model and product_id > 0:
                entry = {
                    "id": product_id,
                    "name": str(product.get("name") or ""),
                    "category": str(category.get("code") or ""),
                }
                entries.append((model, entry))
    return entries


async def fetch_cloud_answers(call: CloudCall) -> tuple[Any, Any]:
    """Fetch the product list, then the Android plugin records of all its products in one request."""
    products = await call(PRODUCTS_PATH)
    product_ids = sorted({entry["id"] for _, entry in _product_entries(products)})
    if not product_ids:
        raise RuntimeError(f"{PRODUCTS_PATH} listed no product with a numeric id")
    body = {"type": APP_TYPE_ANDROID, "apilevel": APP_API_LEVEL, "productids": product_ids}
    records = await call(APPPLUGIN_PATH, method="post", json_body=body)
    return products, records


def build_catalog(products: Any, records: Any, *, base_url: str, fetched_at_utc: str) -> dict[str, Any]:
    plugin_records = [dict(record) for record in records or [] if isinstance(record, dict)]
    return {
        "_comment": "Generated by scripts/refresh_device_plugin_catalog.py. Do not edit by hand.",
        "source": {
            "base_url": base_url,
            "fetched_at_utc": fetched_at_utc,
            "products": f"GET {PRODUCTS_PATH}",
            "appplugin": f"POST {APPPLUGIN_PATH} with type {APP_TYPE_ANDROID} and apilevel {APP_API_LEVEL}",
        },
        "products": dict(sorted(_product_entries(products), key=lambda item: item[0])),
        "appplugin": sorted(plugin_records, key=lambda record: as_int(record.get("productid"), 0)),
    }


async def _login(args: argparse.Namespace, session: aiohttp.ClientSession) -> tuple[RoborockApiClient, UserData]:
    if args.source_json:
        username, base_url, user_data = importer._load_source_from_json_file(
            source_file=args.source_json,
            base_url_override=args.base_url,
        )
        api = RoborockApiClient(username=username, base_url=base_url, session=session)
        return api, UserData.from_dict(user_data)
    email = (args.email or input("Roborock account email: ")).strip()
    api = RoborockApiClient(username=email, base_url=args.base_url, session=session)
    await api.request_code_v4()
    code = input("Login code from the Roborock email: ").strip()
    return api, await api.code_login_v4(code)


async def _main_async(args: argparse.Namespace) -> None:
    timeout = aiohttp.ClientTimeout(total=120)
    async with aiohttp.ClientSession(timeout=timeout) as session:
        api, user_data = await _login(args, session)

        async def call(path: str, *, method: str = "get", json_body: dict[str, Any] | None = None) -> Any:
            return await importer._request_cloud_api_data(api, user_data, path, method=method, json_body=json_body)

        products, records = await fetch_cloud_answers(call)
        base_url = str(await api.base_url)
    catalog = build_catalog(
        products,
        records,
        base_url=base_url,
        fetched_at_utc=datetime.now(UTC).isoformat(),
    )
    args.output.write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    ids_with_record = {as_int(record.get("productid"), 0) for record in catalog["appplugin"]}
    without_record = [model for model, entry in catalog["products"].items() if entry["id"] not in ids_with_record]
    print(f"Wrote {args.output}: {len(catalog['products'])} products, {len(catalog['appplugin'])} plugin records.")
    if without_record:
        print(f"No Android plugin record: {', '.join(without_record)}")


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--email", help="Roborock account email for a code login.")
    parser.add_argument("--source-json", type=Path, help="Stored login, as for import_web_inventory_from_cloud.py.")
    parser.add_argument("--base-url", help="Cloud API base URL, for example https://euiot.roborock.com.")
    parser.add_argument(
        "--output",
        type=Path,
        default=CATALOG_PATH,
        help="Catalog to write (default: shared/device_plugin_catalog.json in the bundled backend).",
    )
    return parser.parse_args()


def main() -> int:
    asyncio.run(_main_async(_parse_args()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
